#!/usr/bin/env bash
# Lattice — assemble + (re)install the widget suite.
#
#   ./build.sh             assemble shared lib into each widget, then install
#   ./build.sh assemble    only copy shared components in (no install)
#   ./build.sh <id>        build+install a single widget (e.g. ./build.sh core)
#   ./build.sh restart     just restart plasmashell
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHARED="$ROOT/shared/ui"
WIDGETS_DIR="$ROOT/widgets"

# qmldir is generated from whatever .qml files live in shared/ui.
gen_qmldir() {
    local dest="$1"
    {
        echo "# generated by build.sh — do not edit"
        for f in "$SHARED"/*.qml; do
            local base name
            base="$(basename "$f")"
            name="${base%.qml}"
            if grep -q "pragma Singleton" "$f"; then
                echo "singleton $name $base"
            else
                echo "$name $base"
            fi
        done
    } > "$dest/qmldir"
}

assemble_one() {
    local wdir="$1"
    local lib="$wdir/contents/ui/lattice"
    rm -rf "$lib"
    mkdir -p "$lib"
    cp "$SHARED"/*.qml "$lib"/
    gen_qmldir "$lib"
    echo "  · assembled $(basename "$wdir")"
}

install_one() {
    local wdir="$1"
    local id
    id="$(grep -oP '"Id"\s*:\s*"\K[^"]+' "$wdir/metadata.json" | head -1)"
    if kpackagetool6 --type Plasma/Applet --show "$id" >/dev/null 2>&1; then
        kpackagetool6 --type Plasma/Applet -u "$wdir"
    else
        kpackagetool6 --type Plasma/Applet -i "$wdir"
    fi
}

# Restart plasmashell through its systemd user unit so it gets the session
# environment, not this shell's. Launching it from a terminal leaks the shell's
# env (e.g. Conda's __EGL_VENDOR_LIBRARY_DIRS) into plasmashell and every app it
# launches afterwards, which breaks GPU acceleration (Electron apps fall back to
# CPU rendering and lag/freeze).
restart_shell() {
    echo "↻ restarting plasmashell…"
    if systemctl --user cat plasma-plasmashell.service >/dev/null 2>&1; then
        if ! systemctl --user is-active --quiet plasma-plasmashell.service; then
            # a stray instance started outside systemd would otherwise survive
            kquitapp6 plasmashell >/dev/null 2>&1 || killall plasmashell 2>/dev/null || true
            sleep 1
        fi
        systemctl --user restart plasma-plasmashell.service
    else
        kquitapp6 plasmashell >/dev/null 2>&1 || killall plasmashell 2>/dev/null || true
        sleep 1
        (setsid env -u __EGL_VENDOR_LIBRARY_DIRS plasmashell >/dev/null 2>&1 &) || true
    fi
    echo "✓ plasmashell relaunched"
}

case "${1:-all}" in
    assemble)
        for w in "$WIDGETS_DIR"/*/; do assemble_one "$w"; done
        ;;
    restart)
        restart_shell
        ;;
    all)
        for w in "$WIDGETS_DIR"/*/; do assemble_one "$w"; install_one "$w"; done
        echo "✓ installed. Add via: right-click desktop → Add Widgets → search 'Lattice'"
        ;;
    *)
        w="$WIDGETS_DIR/org.lattice.$1"
        [ -d "$w" ] || { echo "no such widget: $1"; exit 1; }
        assemble_one "$w"; install_one "$w"
        echo "✓ installed org.lattice.$1"
        ;;
esac
